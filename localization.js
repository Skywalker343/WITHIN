  function translateText(value, locale = "zh") {
    if (locale !== "zh" || !value) return value;
    const leading = value.match(/^\s*/)?.[0] || "";
    const trailing = value.match(/\s*$/)?.[0] || "";
    const core = value.slice(leading.length, value.length - trailing.length || undefined);
    if (!core) return value;
    if (Object.prototype.hasOwnProperty.call(zh, core)) return `${leading}${zh[core]}${trailing}`;
    let match = core.match(/^Good evening, (.+)\.$/);
    if (match) return `${leading}晚上好，${match[1]}。${trailing}`;
    match = core.match(/^(\d+) of (\d+) moments$/);
    if (match) return `${leading}已完成 ${match[1]}/${match[2]} 个片段${trailing}`;
    match = core.match(/^(\d+) \/ (\d+) MOMENTS$/);
    if (match) return `${leading}${match[1]} / ${match[2]} 个片段${trailing}`;
    match = core.match(/^(\d+) spaces$/);
    if (match) return `${leading}${match[1]} 个空间${trailing}`;
    match = core.match(/^(\d+) values · updated today$/);
    if (match) return `${leading}${match[1]} 个价值 · 今日更新${trailing}`;
    match = core.match(/^(.+) · (\d+) min$/);
    if (match) return `${leading}${translateText(match[1], locale)} · ${match[2]} 分钟${trailing}`;
    match = core.match(/^You kept “(.+)” in view\.$/);
    if (match) return `${leading}你记下了“${translateText(match[1], locale)}”。${trailing}`;
    match = core.match(/^Marker found: (.+)$/);
    if (match) return `${leading}已发现标记：${match[1]}${trailing}`;
    let translated = core;
    for (const [english, chinese] of Object.entries(phraseTokens).sort((a, b) => b[0].length - a[0].length)) {
      translated = translated.replaceAll(english, chinese);
    }
    return `${leading}${translated}${trailing}`;
  }

  function translateTree(root, locale = "zh") {
    if (!root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const node of nodes) {
      if (node.parentElement?.closest("textarea, input, script, style, [data-no-translate]")) continue;
      if (node.__withinEnglishText === undefined) node.__withinEnglishText = node.nodeValue;
      node.nodeValue = locale === "zh" ? translateText(node.__withinEnglishText, locale) : node.__withinEnglishText;
    }
    const elements = root.querySelectorAll ? [root, ...root.querySelectorAll("*")] : [root];
    for (const element of elements) {
      if (!(element instanceof Element)) continue;
      for (const attribute of ["placeholder", "aria-label", "title", "alt"]) {
        if (!element.hasAttribute(attribute)) continue;
        element.__withinEnglishAttrs ||= {};
        if (element.__withinEnglishAttrs[attribute] === undefined) element.__withinEnglishAttrs[attribute] = element.getAttribute(attribute);
        const original = element.__withinEnglishAttrs[attribute];
        element.setAttribute(attribute, locale === "zh" ? translateText(original, locale) : original);
      }
      if (element.tagName.toLowerCase() === "a-text" && element.hasAttribute("value")) {
        element.__withinEnglishAttrs ||= {};
        if (element.__withinEnglishAttrs.value === undefined) element.__withinEnglishAttrs.value = element.getAttribute("value");
        const original = element.__withinEnglishAttrs.value;
        element.setAttribute("value", locale === "zh" ? translateText(original, locale) : original);
      }
    }
  }

  window.withinI18n = { translateText, translateTree };
